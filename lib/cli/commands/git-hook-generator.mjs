import fs from 'fs';
import path from 'path';
import { compileAndSaveValidator } from '../../core/rule-compiler.mjs';

/**
 * Installs or updates the Git pre-commit hook in the repository.
 * @param {Object} options
 * @param {string} [options.cwd] Working directory.
 * @returns {{ installed: boolean, hookPath: string }} Installation result.
 */
export function installGitPreCommitHook({ cwd = process.cwd() } = {}) {
  const gitDir = path.join(cwd, '.git');
  if (!fs.existsSync(gitDir)) {
    return { installed: false, hookPath: '', reason: 'Not a git repository' };
  }

  const validatorPath = compileAndSaveValidator({ cwd });

  const hooksDir = path.join(gitDir, 'hooks');
  if (!fs.existsSync(hooksDir)) {
    fs.mkdirSync(hooksDir, { recursive: true });
  }

  const preCommitHookPath = path.join(hooksDir, 'pre-commit');

  const hookContent = `#!/bin/sh
# Auto-generated by Agentic Senior Core (ASC) Adaptive Preference Gate
node .asc/hooks/pre-commit-validator.cjs
`;

  fs.writeFileSync(preCommitHookPath, hookContent, { encoding: 'utf8', mode: 0o755 });

  return { installed: true, hookPath: preCommitHookPath, validatorPath };
}
